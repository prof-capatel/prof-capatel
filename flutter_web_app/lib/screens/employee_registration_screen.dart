  String _tenantSlug = '';
  bool _isCorporate = true;

  List<Map<String, dynamic>> _departments = [];
  int? _selectedDepartmentId;
  String _selectedDepartmentName = 'General';
  bool _isCustomDept = false;

  static const List<_AngleGuide> _angles = [
    _AngleGuide(
      key: 'frontal',
      title: 'Front Angle',
      instruction: '1/3: Look straight into the camera',
