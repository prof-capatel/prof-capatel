  final Map<String, Uint8List> _capturedSamples = {};

  @override
  void initState() {
    super.initState();
    _initAutoGeneratedCode();
    _initTenantAndCamera();
  }

  void _initAutoGeneratedCode() {
    final randomNum = 1000 + Random().nextInt(9000);
    _rollCtrl.text = 'EMP-$randomNum';
  }

  Future<void> _initTenantAndCamera() async {
    final auth = context.read<AuthProvider>();
    _tenantSlug = auth.tenantSlug.isNotEmpty && auth.tenantSlug != 'default'
        ? auth.tenantSlug
        : 'default';
    _tenantName = auth.tenantName.isNotEmpty ? auth.tenantName : _tenantSlug;

    try {
      // 1. Resolve current tenant to ensure UUID & onboarding token are available
      final res = await ApiService.resolveTenant(_tenantSlug);
      final tenantData = res['tenant'] ?? {};
      _tenantUuid = tenantData['uuid'] ?? _tenantSlug;
      _onboardingToken = tenantData['onboarding_token'] ?? '';
      _tenantName = tenantData['name'] ?? _tenantName;
      _isCorporate = (tenantData['tenant_type'] ?? 'corporate') == 'corporate';

      // 2. Fetch tenant onboarding metadata & department list
      if (_tenantUuid.isNotEmpty && _onboardingToken.isNotEmpty) {
        try {
          final info = await ApiService.getOnboardInfo(
            tenantUuid: _tenantUuid,
            onboardingToken: _onboardingToken,
          );
          if (mounted) {
            final rawDepts = info['departments'] as List<dynamic>? ?? [];
            setState(() {
              _departments = rawDepts.map((d) => Map<String, dynamic>.from(d as Map)).toList();
              if (_departments.isNotEmpty) {
                _selectedDepartmentId = _departments.first['id'] as int?;
                _selectedDepartmentName = _departments.first['name'] as String? ?? 'General';
              }
              if (info['suggested_code'] != null && _rollCtrl.text.isEmpty) {
                _rollCtrl.text = info['suggested_code'].toString();
              }
            });
          }
        } catch (_) {
          // Graceful fallback to default departments
        }
      }

      // 3. Initialize front camera for biometric enrollment
      await _cameraService.initialize(useFrontCamera: true);
      if (mounted) {
        setState(() {
          _isCameraReady = true;
          _errorMessage = null;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _errorMessage = ErrorFormatter.format(e);
          _isCameraReady = false;
        });
      }
    }
  }

  @override
  void dispose() {
    _nameCtrl.dispose();
    _rollCtrl.dispose();
    _emailCtrl.dispose();
    _customDeptCtrl.dispose();
    _cameraService.dispose();
    super.dispose();
  }

  Future<void> _captureCurrentAngle() async {
    if (_isCapturing || !_isCameraReady) return;

    setState(() {
      _isCapturing = true;
      _errorMessage = null;
    });

    try {
      final frameBytes = await _cameraService.captureFrame();
      if (frameBytes == null) {
        throw Exception('Could not capture photo. Please check camera permissions.');
      }

      final activeAngle = _angles[_currentAngleIndex];
      _capturedSamples[activeAngle.key] = frameBytes;

      // Advance to next angle if not complete
      if (_currentAngleIndex < _angles.length - 1) {
        _currentAngleIndex++;
      }

      if (mounted) {
        setState(() {
          _isCapturing = false;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _errorMessage = ErrorFormatter.format(e);
          _isCapturing = false;
        });
      }
    }
  }

  void _resetCaptures() {
    setState(() {
      _capturedSamples.clear();
      _currentAngleIndex = 0;
      _errorMessage = null;
    });
  }

  Future<void> _handleSubmitRegistration() async {
    if (!_formKey.currentState!.validate()) return;

    if (_capturedSamples.length < 3) {
      setState(() {
        _errorMessage = 'Please capture all 3 face biometric angles (Front, Left, Right) to complete registration.';
      });
      return;
    }

    if (_tenantUuid.isEmpty || _onboardingToken.isEmpty) {
      setState(() {
        _errorMessage = 'Organization onboarding token is unavailable. Please verify organization setup.';
      });
      return;
    }

    setState(() {
      _isSubmitting = true;
      _errorMessage = null;
      _statusMessage = 'Registering employee profile...';
    });

    final enteredName = _nameCtrl.text.trim();
    final enteredCode = _rollCtrl.text.trim().toUpperCase();
    final enteredEmail = _emailCtrl.text.trim();
    final deptName = _isCustomDept
        ? _customDeptCtrl.text.trim()
        : _selectedDepartmentName;

    try {
      // Step 1: Register Profile via tokenized onboarding API
      final regRes = await ApiService.registerEmployeeOnboard(
        tenantUuid: _tenantUuid,
        onboardingToken: _onboardingToken,
        name: enteredName,
        rollNumber: enteredCode,
        email: enteredEmail.isNotEmpty ? enteredEmail : null,
        departmentId: _isCustomDept ? null : _selectedDepartmentId,
        department: deptName.isNotEmpty ? deptName : 'General',
      );

      final studentData = regRes['student'] as Map<String, dynamic>?;
      final studentId = studentData?['id'] as int?;

      if (studentId == null) {
        throw Exception('Profile registration did not return a valid profile ID.');
      }

      // Step 2: Upload Biometric Samples for all 3 angles
      for (int i = 0; i < _angles.length; i++) {
        final angle = _angles[i];
        final sampleBytes = _capturedSamples[angle.key];
        if (sampleBytes == null) continue;

        if (mounted) {
          setState(() {
            _statusMessage = 'Indexing face biometric (${i + 1}/3: ${angle.title})...';
          });
        }

        await ApiService.uploadOnboardFaceSample(
          tenantUuid: _tenantUuid,
          onboardingToken: _onboardingToken,
          studentId: studentId,
          sampleAngle: angle.key,
          imageBytes: sampleBytes,
        );
      }

      if (!mounted) return;

      setState(() {
        _isSubmitting = false;
        _statusMessage = null;
      });

      // Step 3: Show Success Confirmation Dialog
      _showRegistrationSuccessDialog(
        name: enteredName,
        code: enteredCode,
        department: deptName,
      );
    } catch (e) {
      if (mounted) {
        setState(() {
          _errorMessage = ErrorFormatter.format(e);
          _isSubmitting = false;
          _statusMessage = null;
        });
      }
    }
  }

