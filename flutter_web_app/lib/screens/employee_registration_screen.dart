                              margin: EdgeInsets.only(
                                left: idx == 0 ? 0 : 4,
                                right: idx == _angles.length - 1 ? 0 : 4,
                              ),
                              padding: const EdgeInsets.all(6),
                              decoration: BoxDecoration(
                                color: isDark ? const Color(0xFF161B22) : Colors.white,
                                borderRadius: BorderRadius.circular(12),
                                border: Border.all(
                                  color: isCaptured
                                      ? const Color(0xFF10B981)
                                      : (isCurrent ? const Color(0xFF6366F1) : (isDark ? Colors.white12 : const Color(0xFFE2E8F0))),
                                  width: isCurrent || isCaptured ? 1.8 : 1,
                                ),
                              ),
                              child: Column(
                                children: [
                                  Container(
                                    height: 52,
                                    width: double.infinity,
                                    decoration: BoxDecoration(
                                      color: isDark ? const Color(0xFF0D1117) : const Color(0xFFF1F5F9),
                                      borderRadius: BorderRadius.circular(8),
                                    ),
                                    clipBehavior: Clip.antiAlias,
                                    child: isCaptured
                                        ? Stack(
                                            fit: StackFit.expand,
                                            children: [
                                              Image.memory(sample, fit: BoxFit.cover),
                                              Positioned(
                                                top: 2,
                                                right: 2,
                                                child: Container(
                                                  padding: const EdgeInsets.all(2),
                                                  decoration: const BoxDecoration(
                                                    color: Color(0xFF10B981),
                                                    shape: BoxShape.circle,
                                                  ),
                                                  child: const Icon(Icons.check, size: 10, color: Colors.white),
                                                ),
                                              ),
                                            ],
                                          )
                                        : Center(
                                            child: Icon(
                                              angle.icon,
                                              size: 20,
                                              color: isCurrent
                                                  ? const Color(0xFF6366F1)
                                                  : (isDark ? Colors.white30 : Colors.black26),
                                            ),
                                          ),
                                  ),
                                  const SizedBox(height: 4),
                                  Text(
                                    angle.title,
                                    style: TextStyle(
                                      color: isCaptured
                                          ? const Color(0xFF10B981)
                                          : (isDark ? Colors.white70 : const Color(0xFF475569)),
                                      fontSize: 10.5,
                                      fontWeight: isCaptured || isCurrent ? FontWeight.bold : FontWeight.normal,
                                    ),
                                  ),
                                ],
                              ),
                            ),
                          ),
                        );
                      }),
                    ),
                    const SizedBox(height: 14),

                    // Error Notification Banner
                    if (_errorMessage != null)
                      Container(
                        padding: const EdgeInsets.all(12),
                        margin: const EdgeInsets.only(bottom: 12),
                        decoration: BoxDecoration(
                          color: const Color(0xFFEF4444).withOpacity(0.14),
